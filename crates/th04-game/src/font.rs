//! A compact built-in 5×7 bitmap font (uppercase letters, digits, a little
//! punctuation), drawn as solid white-texture rectangles. Used for the
//! title/menu text and any debug labels until the authentic `GAMEFT.BFT` font
//! is wired in. Each glyph is 7 rows of 5 bits (bit 4 = leftmost column).

use th06_engine::DrawCmd;

/// Glyph cell: 5 wide × 7 tall.
pub const GLYPH_W: usize = 5;
pub const GLYPH_H: usize = 7;

/// 7 rows, low 5 bits each (MSB = left column). `None` → unsupported → blank.
fn glyph(c: char) -> Option<[u8; 7]> {
    Some(match c.to_ascii_uppercase() {
        ' ' => [0, 0, 0, 0, 0, 0, 0],
        'A' => [0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'B' => [0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E],
        'C' => [0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E],
        'D' => [0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E],
        'E' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F],
        'F' => [0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10],
        'G' => [0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0E],
        'H' => [0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11],
        'I' => [0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E],
        'J' => [0x07, 0x02, 0x02, 0x02, 0x12, 0x12, 0x0C],
        'K' => [0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11],
        'L' => [0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F],
        'M' => [0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11],
        'N' => [0x11, 0x11, 0x19, 0x15, 0x13, 0x11, 0x11],
        'O' => [0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'P' => [0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10],
        'Q' => [0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D],
        'R' => [0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11],
        'S' => [0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E],
        'T' => [0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04],
        'U' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E],
        'V' => [0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04],
        'W' => [0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11],
        'X' => [0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11],
        'Y' => [0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04],
        'Z' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F],
        '0' => [0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E],
        '1' => [0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E],
        '2' => [0x0E, 0x11, 0x01, 0x06, 0x08, 0x10, 0x1F],
        '3' => [0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E],
        '4' => [0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02],
        '5' => [0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E],
        '6' => [0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E],
        '7' => [0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08],
        '8' => [0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E],
        '9' => [0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C],
        '-' => [0, 0, 0, 0x1F, 0, 0, 0],
        '.' => [0, 0, 0, 0, 0, 0x06, 0x06],
        ':' => [0, 0x06, 0x06, 0, 0x06, 0x06, 0],
        '!' => [0x04, 0x04, 0x04, 0x04, 0x04, 0, 0x04],
        '~' => [0, 0, 0x08, 0x15, 0x02, 0, 0],
        _ => return None,
    })
}

/// Pixel advance per character at scale `px` (5 columns + 1 column gap).
pub fn advance(px: f32) -> f32 {
    (GLYPH_W as f32 + 1.0) * px
}

/// Width in pixels a string occupies at scale `px`.
pub fn text_width(text: &str, px: f32) -> f32 {
    text.chars().count() as f32 * advance(px)
}

/// Draw `text` with its top-left at (`x`, `y`); each font pixel is a `px`×`px`
/// solid quad of `color` on the white texture (index 0).
pub fn draw_text(cmds: &mut Vec<DrawCmd>, x: f32, y: f32, text: &str, px: f32, color: [f32; 4]) {
    let mut cx = x;
    for ch in text.chars() {
        if let Some(g) = glyph(ch) {
            for (row, bits) in g.iter().enumerate() {
                for col in 0..GLYPH_W {
                    if bits & (0b10000 >> col) != 0 {
                        cmds.push(DrawCmd {
                            tex: 0,
                            dst: [cx + col as f32 * px, y + row as f32 * px, px, px],
                            src: [0.0, 0.0, 1.0, 1.0],
                            tint: color,
                            rot: 0.0,
                        });
                    }
                }
            }
        }
        cx += advance(px);
    }
}

/// Draw `text` centred horizontally on `cx`, top at `y`.
pub fn draw_text_centered(cmds: &mut Vec<DrawCmd>, cx: f32, y: f32, text: &str, px: f32, color: [f32; 4]) {
    draw_text(cmds, cx - text_width(text, px) / 2.0, y, text, px, color);
}
